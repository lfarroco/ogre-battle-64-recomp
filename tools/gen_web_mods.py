#!/usr/bin/env python3
"""Generate the C++ for the browser build's bundled code mods.

The browser has no runtime code generation (see the wasm stub in
`tools/N64ModernRuntime/N64Recomp/LiveRecomp/live_generator_wasm.cpp`), so a
`.nrm` code mod cannot be live-recompiled the way the native build does it.
Instead the mod's MIPS is recompiled ahead of time with N64Recomp's
`OfflineModRecomp`, and the resulting C is compiled into the wasm app. The mod is
still installed as a normal embedded `.nrm`: manifest, config options and the
on/off state all come from the mod system (`librecomp/src/mods.cpp`,
`recomp::mods::register_embedded_mod`). Only code loading differs, through the
`recomp::mods::StaticModInfo` table this script generates.

Inputs, all produced on a machine that has the ROM:

    build/mods/*.nrm                 `make example-mods`
    mods/*/build/mod.elf             the same build (its .recomp_hook sections
                                     name the game functions to instrument)
    mods/reference/dump.toml         `make mod-syms`
    tools/N64Recomp/build/OfflineModRecomp
    mips-linux-gnu-readelf           the MIPS binutils

Outputs (gitignored; the private data bundle ships them to CI):

    app/src/web_mods/bundled_mods.h
    app/src/web_mods/bundled_mods.cpp
    app/src/web_mods/<mod id>.cpp

Usage:
    python3 tools/gen_web_mods.py                 # every .nrm in build/mods/
    python3 tools/gen_web_mods.py --mods DIR      # another directory of .nrm
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_MODS = ROOT / "build" / "mods"
OUT_DIR = ROOT / "app" / "src" / "web_mods"
REFERENCE = ROOT / "mods" / "reference" / "dump.toml"
OFFLINE = ROOT / "tools" / "N64Recomp" / "build" / "OfflineModRecomp"
READELF = "mips-linux-gnu-readelf"

HEADER = """\
// Generated by tools/gen_web_mods.py. Do not edit.
//
// One entry per built-in `.nrm` the browser build ships. The bytes are the same
// archive the native package puts in `mods/`, embedded so the page does not have
// to fetch them and so a subpath deployment needs no extra request.
#ifndef OGRE_BUNDLED_MODS_H
#define OGRE_BUNDLED_MODS_H

#include <stddef.h>

struct OgreWebModEntry {
    const char* id;
    const unsigned char* bytes;
    unsigned int size;
};

// The embedded archives, in the order the generator wrote them.
const OgreWebModEntry* ogre_web_mod_entries(size_t* count);

#endif  // OGRE_BUNDLED_MODS_H
"""


def fail(message: str) -> None:
    print(f"gen_web_mods.py: {message}", file=sys.stderr)
    raise SystemExit(1)


def c_array(name: str, data: bytes) -> str:
    lines = [f"static const unsigned char {name}[] = {{"]
    for start in range(0, len(data), 16):
        chunk = data[start:start + 16]
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")
    lines.append("};")
    return "\n".join(lines)


def run_offline_recomp(nrm: Path, symbols: Path, work: Path) -> tuple[dict, str]:
    with zipfile.ZipFile(nrm) as archive:
        names = set(archive.namelist())
        for required in ("mod.json", "mod_syms.bin", "mod_binary.bin"):
            if required not in names:
                fail(f"{nrm.name} has no {required}")
        manifest = json.loads(archive.read("mod.json").decode("utf-8"))
        archive.extract("mod_syms.bin", work)
        archive.extract("mod_binary.bin", work)

    output = work / "out.c"
    result = subprocess.run(
        [
            str(OFFLINE),
            str(work / "mod_syms.bin"),
            str(work / "mod_binary.bin"),
            str(symbols),
            str(output),
        ],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        fail(f"OfflineModRecomp failed for {nrm.name}: {result.stderr.strip()}")
    body = output.read_text()
    body = body.replace('#include "mod_recomp.h"\n\n', "", 1)
    return manifest, body


def mod_elf_for(nrm: Path) -> Path:
    """The mod's linked MIPS ELF, which carries its .recomp_hook sections."""
    direct = ROOT / "mods" / nrm.stem / "build" / "mod.elf"
    if direct.is_file():
        return direct
    for toml in sorted((ROOT / "mods").glob("*/mod.toml")):
        text = toml.read_text()
        if re.search(rf'mod_filename\s*=\s*"{re.escape(nrm.stem)}"', text):
            candidate = toml.parent / "build" / "mod.elf"
            if candidate.is_file():
                return candidate
    fail(
        f"cannot find the linked ELF for {nrm.name}; run 'make example-mods' first"
    )


def hook_targets(elf: Path) -> tuple[list[tuple[str, int]], list[tuple[str, int]]]:
    """(entry hooks, replacements) as (name, vram) from the mod's sections.

    A hook's target is the game function named in the `.recomp_hook.<name>`
    section. A replacement names the original function in its own symbol, since
    the section is just `.recomp_patch`. Both names are `func_<8 hex digits>` for
    the main unit, which is the only unit a code mod can hook.
    """
    sections = subprocess.run(
        [READELF, "-SW", str(elf)], capture_output=True, text=True, check=True
    ).stdout
    section_names: dict[int, str] = {}
    for line in sections.splitlines():
        match = re.match(r"\s*\[\s*(\d+)\]\s+(\S+)", line)
        if match is not None:
            section_names[int(match.group(1))] = match.group(2)

    symbols = subprocess.run(
        [READELF, "-sW", str(elf)], capture_output=True, text=True, check=True
    ).stdout
    symbols_by_section: dict[int, list[str]] = {}
    for line in symbols.splitlines():
        match = re.match(
            r"\s*\d+:\s+[0-9a-fA-F]+\s+\d+\s+\S+\s+\S+\s+\S+\s+(\d+)\s+(\S+)\s*$",
            line,
        )
        if match is not None:
            symbols_by_section.setdefault(int(match.group(1)), []).append(match.group(2))

    def vram_of(name: str) -> int:
        match = re.fullmatch(r"func_([0-9A-Fa-f]{8})", name)
        if match is None:
            fail(f"{elf}: '{name}' is not a main-unit function name")
        return int(match.group(1), 16)

    hooks: list[tuple[str, int]] = []
    patches: list[tuple[str, int]] = []
    for index, name in section_names.items():
        if name.startswith(".recomp_hook_return."):
            fail(
                f"{elf}: {name} is a return hook; the browser build only has an "
                "entry call site for bundled mods"
            )
        if name.startswith(".recomp_hook."):
            target = name[len(".recomp_hook."):]
            hooks.append((target, vram_of(target)))
        elif name in (".recomp_patch", ".recomp_force_patch"):
            originals = [
                symbol
                for symbol in symbols_by_section.get(index, [])
                if re.fullmatch(r"func_[0-9A-Fa-f]{8}", symbol)
            ]
            if not originals:
                fail(f"{elf}: {name} has no func_<vram> symbol")
            for original in originals:
                patches.append((original, vram_of(original)))
    return hooks, patches


def parse_generated(body: str, nrm: Path) -> dict:
    def count(pattern: str, what: str) -> int:
        match = re.search(pattern, body)
        if match is None:
            fail(f"{nrm.name}: could not find {what} in the recompiled C")
        return int(match.group(1))

    imported = count(r"recomp_func_t\* imported_funcs\[(\d+)\]", "imported_funcs")
    reference = count(
        r"recomp_func_t\* reference_symbol_funcs\[(\d+)\]", "reference_symbol_funcs"
    )
    sections = count(r"int32_t section_addresses\[(\d+)\]", "section_addresses")

    prototypes = re.findall(
        r"^RECOMP_FUNC void ([A-Za-z_][A-Za-z0-9_]*)\(uint8_t\* rdram, recomp_context\* ctx\);$",
        body,
        re.MULTILINE,
    )
    if not prototypes:
        fail(f"{nrm.name}: the recompiled C defines no functions")

    return {
        "imported": imported,
        "reference": reference,
        "sections": sections,
        "functions": prototypes,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mods", type=Path, default=DEFAULT_MODS,
                        help="directory holding the .nrm archives")
    parser.add_argument("--out", type=Path, default=OUT_DIR,
                        help="generated output directory")
    args = parser.parse_args()

    if not OFFLINE.is_file():
        fail(f"{OFFLINE.relative_to(ROOT)} is missing; build N64Recomp first")
    if not REFERENCE.is_file():
        fail(f"{REFERENCE.relative_to(ROOT)} is missing; run 'make mod-syms'")
    if not args.mods.is_dir():
        fail(f"{args.mods.relative_to(ROOT)} is missing; run 'make example-mods'")

    archives = sorted(args.mods.glob("*.nrm"))
    if not archives:
        fail(f"no .nrm archives in {args.mods.relative_to(ROOT)}")

    args.out.mkdir(parents=True, exist_ok=True)
    # Remove only this generator's output, so a mod that was dropped from
    # build/mods cannot leave a stale translation unit behind.
    for old in list(args.out.glob("*.cpp")) + list(args.out.glob("*.h")) + list(args.out.glob("instrumented.txt")):
        old.unlink()

    entries = []
    targets: set[tuple[str, int]] = set()
    for nrm in archives:
        with tempfile.TemporaryDirectory() as tmp:
            manifest, body = run_offline_recomp(nrm, REFERENCE, Path(tmp))
        info = parse_generated(body, nrm)
        elf = mod_elf_for(nrm)
        hooks, patches = hook_targets(elf)
        for name, vram in hooks:
            targets.add(("entry", vram))
        for name, vram in patches:
            targets.add(("replace", vram))
        mod_id = manifest["id"]
        namespace = re.sub(r"[^A-Za-z0-9_]", "_", mod_id)

        source = f"""\
// Generated by tools/gen_web_mods.py from {nrm.relative_to(ROOT)}. Do not edit.
//
// `{manifest['display_name']}` ({mod_id}) recompiled ahead of time for the wasm
// build. Only the generated functions and their globals live here, in a
// namespace; the `StaticModInfo` table that refers to them is in
// bundled_mods.cpp, so this translation unit does not include recomp.h (whose
// `section_addresses` and `get_function` would collide with the mod's own).
#include "web_mod_recomp.h"

namespace ogre_mod_{namespace} {{
#line 1 "{nrm.stem}-recomp.c"
{body}
}}  // namespace ogre_mod_{namespace}
"""
        (args.out / f"{mod_id}.cpp").write_text(source)
        entries.append({"manifest": manifest, "namespace": namespace,
                        "bytes": nrm.read_bytes(), "info": info})

    registry = [
        "// Generated by tools/gen_web_mods.py. Do not edit.",
        '#include "bundled_mods.h"',
        "",
        '#include "librecomp/mods.hpp"',
        "",
        "#include <cstring>",
        "",
    ]
    declarations = []
    table = []
    find_body = []
    for entry in entries:
        manifest = entry["manifest"]
        namespace = entry["namespace"]
        data = entry["bytes"]
        info = entry["info"]
        declarations.append(
            f"extern \"C\" const recomp::mods::StaticModInfo ogre_static_mod_{namespace};"
        )
        registry.append(c_array(f"kBytes_{namespace}", data))
        registry.append("")
        table.append(
            f'    {{"{namespace}", kBytes_{namespace}, sizeof(kBytes_{namespace})}},'
        )
        find_body.append(
            f'    if (std::strcmp(mod_id, "{namespace}") == 0) {{\n'
            f"        return &ogre_static_mod_{namespace};\n"
            f"    }}"
        )

    # The mods' generated TUs are compiled without recomp.h; declare the globals
    # they define, then build the static handle's table here, where the runtime's
    # types are available.
    body = []
    for entry in entries:
        namespace = entry["namespace"]
        info = entry["info"]
        functions = ",\n".join(
            f"    &ogre_mod_{namespace}::{name}" for name in info["functions"]
        )
        body.append(f"""\
namespace ogre_mod_{namespace} {{
{os.linesep.join(f"void {name}(uint8_t* rdram, recomp_context* ctx);" for name in info["functions"])}
extern recomp_func_t* imported_funcs[{info['imported']}];
extern recomp_func_t* reference_symbol_funcs[{info['reference']}];
extern int32_t section_addresses[{info['sections']}];
extern uint32_t base_event_index;
extern void (*recomp_trigger_event)(uint8_t* rdram, recomp_context* ctx, uint32_t index);
extern recomp_func_t* (*get_function)(int32_t vram);
extern void (*cop0_status_write)(recomp_context* ctx, gpr value);
extern gpr (*cop0_status_read)(recomp_context* ctx);
extern void (*switch_error)(const char* func, uint32_t vram, uint32_t jtbl);
extern void (*do_break)(uint32_t vram);
extern int32_t* reference_section_addresses;
}}  // namespace ogre_mod_{namespace}

namespace {{
recomp_func_t* const kFunctions_{namespace}[] = {{
{functions},
}};
}}  // namespace

extern \"C\" const recomp::mods::StaticModInfo ogre_static_mod_{namespace} = {{
    "{namespace}",
    1u,
    kFunctions_{namespace},
    {len(info['functions'])},
    ogre_mod_{namespace}::imported_funcs,
    {info['imported']},
    ogre_mod_{namespace}::reference_symbol_funcs,
    {info['reference']},
    &ogre_mod_{namespace}::base_event_index,
    &ogre_mod_{namespace}::recomp_trigger_event,
    &ogre_mod_{namespace}::get_function,
    &ogre_mod_{namespace}::cop0_status_write,
    &ogre_mod_{namespace}::cop0_status_read,
    &ogre_mod_{namespace}::switch_error,
    &ogre_mod_{namespace}::do_break,
    &ogre_mod_{namespace}::reference_section_addresses,
    ogre_mod_{namespace}::section_addresses,
    {info['sections']},
}};
""")

    registry.extend(declarations)
    registry.append("")
    registry.extend(body)
    registry.append("namespace {")
    registry.append("const OgreWebModEntry kEntries[] = {")
    registry.extend(table)
    registry.append("};")
    registry.append("}  // namespace")
    registry.append("")
    registry.append("const OgreWebModEntry* ogre_web_mod_entries(size_t* count) {")
    registry.append("    *count = sizeof(kEntries) / sizeof(kEntries[0]);")
    registry.append("    return kEntries;")
    registry.append("}")
    registry.append("")
    registry.append("// Called by librecomp when a wasm build loads a code mod. Returning")
    registry.append("// nullptr means the mod has no precompiled body, which is a load error.")
    registry.append("extern \"C\" const recomp::mods::StaticModInfo* recomp_find_static_mod(")
    registry.append("    const char* mod_id) {")
    registry.extend(find_body)
    registry.append("    return nullptr;")
    registry.append("}")
    (args.out / "bundled_mods.cpp").write_text("\n".join(registry) + "\n")
    (args.out / "bundled_mods.h").write_text(HEADER)

    # The game functions the generated code needs a call site in. A hook's call
    # goes at the function's entry; a replacement's call sits there too and runs
    # the mod's function instead of the body. tools/web_mod_hooks.py applies the
    # list to RecompiledFuncs/.
    lines = ["# Generated by tools/gen_web_mods.py. Do not edit.",
             "# <kind> <game function vram>"]
    for kind, vram in sorted(targets, key=lambda item: (item[0], item[1])):
        lines.append(f"{kind} 0x{vram:08X}")
    (args.out / "instrumented.txt").write_text("\n".join(lines) + "\n")

    print(f"==> {len(entries)} bundled mod(s) -> {args.out.relative_to(ROOT)}")
    for entry in entries:
        manifest = entry["manifest"]
        print(f"    {manifest['id']:28s} {manifest['display_name']}")
    print(f"==> {len(targets)} game function call site(s)")


if __name__ == "__main__":
    main()
